/* Converts the web game's level data (../js/data/levels.js) into src/game/data/levels.ts.
 * The levels are copied exactly; run again whenever the web levels are regenerated.
 *   node scripts/convert-levels.js
 */
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', '..', 'js', 'data', 'levels.js');
const out = path.join(__dirname, '..', 'src', 'game', 'data', 'levels.ts');

const sandbox = {};
new Function('globalThis', 'window', fs.readFileSync(src, 'utf8'))(sandbox, undefined);
const sets = sandbox.BP && sandbox.BP.LEVEL_SETS;
if (!sets || !sets.classic) throw new Error('LEVEL_SETS not found in ' + src);

const body = Object.keys(sets)
  .map((mode) => `  ${mode}: ${JSON.stringify(sets[mode], null, 2).replace(/\n/g, '\n  ')},`)
  .join('\n');

const ts = `/* Ball Roll — level data. GENERATED by scripts/convert-levels.js from the web game's
 * js/data/levels.js — do not edit by hand. One set per mode.
 * rows: tile tokens (see core/tiles.ts); par: BFS-proven minimum moves;
 * solution: [x, y, dirBit] slides from the initial layout.
 */
import type { LevelDef } from '../core/session';
import type { LevelMode } from '../core/constants';

export const LEVEL_SETS: Record<LevelMode, LevelDef[]> = {
${body}
};
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, ts);
console.log('Wrote', Object.keys(sets).map((m) => `${m}: ${sets[m].length}`).join(', '), 'to', path.relative(process.cwd(), out));

// ---- ball skins: js/data/ball-skins.js -> src/game/data/ballSkins.ts ----
{
  const skinsSrc = path.join(__dirname, '..', '..', 'js', 'data', 'ball-skins.js');
  const skinsOut = path.join(__dirname, '..', 'src', 'game', 'data', 'ballSkins.ts');
  delete require.cache[require.resolve(skinsSrc)];
  const BallSkins = require(skinsSrc);
  const tsSkins = `/* Ball Roll — ball skins. GENERATED by scripts/convert-levels.js from the web game's
 * js/data/ball-skins.js — do not edit by hand. Field meanings are documented there.
 */
export interface BallSkin {
  id: string;
  name: string;
  collection: 'Basic' | 'Premium' | 'Special';
  cost: number;
  sound: string;
  body: [string, string, string];
  alpha?: number;
  halo?: [string, number];
  bands?: { color: string; width: number; count: number }[];
  dots?: { color: string; n: number; r: number }[];
  sweep?: string[];
  twinkle?: { color: string; n: number }[];
  spec?: number;
}

export const BALL_SKINS: BallSkin[] = ${JSON.stringify(BallSkins.SKINS, null, 2)};

export const DEFAULT_BALL = ${JSON.stringify(BallSkins.DEFAULT)};
export const BALL_COLLECTIONS = ${JSON.stringify(BallSkins.COLLECTIONS)} as const;
`;
  fs.writeFileSync(skinsOut, tsSkins);
  console.log('Wrote', BallSkins.SKINS.length, 'ball skins to', path.relative(process.cwd(), skinsOut));
}
