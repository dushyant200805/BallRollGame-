/* Generates js/data/levels.js — run: node tools/generate-levels.js [count]
 * Every level is produced from a seed, scrambled with legal moves only, and its par is
 * the BFS-proven minimum number of moves. Re-running with the same plan gives the same
 * levels.
 */
const fs = require('fs');
const path = require('path');
const BP = require('./load-core')();

// Hand-tuned difficulty ramp for the beginner levels, then a tier formula after.
const BEGINNER = [
  { size: 5, pathMin: 4, pathMax: 5, empties: 3, decoyRatio: 0.25, scramble: 2, parMin: 1, parMax: 1 },
  { size: 5, pathMin: 5, pathMax: 6, empties: 3, decoyRatio: 0.3, scramble: 3, parMin: 2, parMax: 2 },
  { size: 5, pathMin: 5, pathMax: 7, empties: 2, decoyRatio: 0.4, scramble: 5, parMin: 3, parMax: 3 },
  { size: 5, pathMin: 6, pathMax: 7, empties: 2, decoyRatio: 0.4, fixedOnPath: 1, scramble: 6, parMin: 3, parMax: 4 },
  { size: 5, pathMin: 6, pathMax: 8, empties: 2, blocks: 1, decoyRatio: 0.5, fixedOnPath: 1, scramble: 8, parMin: 4, parMax: 5 },
  { size: 5, pathMin: 7, pathMax: 9, empties: 2, blocks: 1, decoyRatio: 0.5, fixedOnPath: 1, scramble: 10, parMin: 5, parMax: 6 },
  { size: 6, pathMin: 7, pathMax: 9, empties: 3, blocks: 1, decoyRatio: 0.5, fixedOnPath: 1, scramble: 10, parMin: 5, parMax: 6 },
  { size: 6, pathMin: 8, pathMax: 10, empties: 2, blocks: 2, decoyRatio: 0.55, fixedOnPath: 1, scramble: 12, parMin: 6, parMax: 7 },
  { size: 6, pathMin: 8, pathMax: 11, empties: 2, blocks: 2, decoyRatio: 0.55, fixedOnPath: 2, scramble: 14, parMin: 7, parMax: 8 },
  { size: 6, pathMin: 9, pathMax: 12, empties: 2, blocks: 2, decoyRatio: 0.6, fixedOnPath: 2, scramble: 16, parMin: 8, parMax: 9 },
];

function planFor(n) {
  if (n <= BEGINNER.length) return BEGINNER[n - 1];
  // Beyond the MVP: scale size, path length and scramble depth with level number.
  const size = n <= 30 ? 6 : 7;
  const par = Math.min(8 + Math.floor((n - 10) / 4), 24);
  return {
    size, pathMin: size + 3, pathMax: size + 7, empties: 2, blocks: n > 30 ? 3 : 2,
    decoyRatio: 0.6, fixedOnPath: n > 60 ? 3 : 2, fixedDecoyChance: n > 60 ? 0.1 : 0,
    scramble: par * 2 + 6, parMin: par, parMax: par + 1, maxNodes: 1500000,
  };
}

const count = parseInt(process.argv[2] || '10', 10);
const levels = [];
for (let n = 1; n <= count; n++) {
  const cfg = planFor(n);
  const t0 = Date.now();
  const res = BP.Generator.generate(cfg, 'ballpath-level-' + n);
  if (!res) {
    console.error(`Level ${n}: generation failed`);
    process.exit(1);
  }
  levels.push({
    id: n,
    size: cfg.size,
    par: res.par,
    rows: res.rows,
    solution: res.solution.map((m) => [m.x, m.y, m.dir]),
  });
  console.log(`Level ${String(n).padStart(3)}  ${cfg.size}x${cfg.size}  par ${String(res.par).padStart(2)}  (${Date.now() - t0} ms)`);
}

const out = `/* Ball Path — level data. GENERATED by tools/generate-levels.js — do not edit by hand.
 * rows: tile tokens (see js/core/tiles.js); par: BFS-proven minimum moves;
 * solution: [x, y, dirBit] slides from the initial layout.
 */
(function (BP) {
  'use strict';
  BP.LEVEL_DATA = [
${levels.map((l) => `    {
      id: ${l.id}, size: ${l.size}, par: ${l.par},
      rows: [
${l.rows.map((r) => `        ${JSON.stringify(r)},`).join('\n')}
      ],
      solution: ${JSON.stringify(l.solution)},
    },`).join('\n')}
  ];
})(typeof window !== 'undefined' ? (window.BP = window.BP || {}) : (globalThis.BP = globalThis.BP || {}));
`;
const target = path.join(__dirname, '..', 'js', 'data', 'levels.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`Wrote ${levels.length} levels to ${path.relative(process.cwd(), target)}`);
